#!/usr/bin/env bun
/**
 * Project a native Muse plugin whose PostToolUse hook emits a `tool.call`
 * substrate event.
 *
 *   bun packages/projector/src/muse.ts
 *
 * Muse's plugin bundle is not itself checked into this repo — this script
 * IS its source, regenerated fresh into `MUSE_PLUGIN_DIR` on every run and
 * installed into Muse's own plugin cache via `muse plugins install --scope
 * user`, then approved so the hook is enabled rather than merely present
 * ("third-party plugin: hooks require review before activation" is Muse's
 * own gate on that). Re-running regenerates the identical bundle and calls
 * `muse plugins update` instead of `install` when a copy is already present,
 * so there is never a second installed copy of the same plugin id.
 *
 * The manifest shape below is not a guess: it is exactly what this host's
 * own Muse binary documents in its bundled `create-plugin` skill reference
 * (`native-plugin-contract.md` / `capability-examples.json`) and what
 * `muse plugins validate` accepts with an empty diagnostics array.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { join } from "node:path";

const MUSE_BIN = process.env.MUSE_BIN ?? "/root/.local/bin/muse";
const BUN_BIN = process.env.SUBSTRATE_BUN_BIN ?? "/root/.local/share/reflex/bun/bin/bun";
const REDACT_MODULE =
	process.env.SUBSTRATE_REDACT_MODULE ?? "/root/src/repos/agent-substrate/packages/mcp-server/src/redact.ts";
const BUNDLE_DIR = process.env.MUSE_PLUGIN_DIR ?? "/var/lib/substrate/muse-plugin";
const PLUGIN_ID = "substrate";
const HOOK_ID = "post-tool-use";

const manifest = {
	schemaVersion: 1,
	name: PLUGIN_ID,
	displayName: "Substrate Event Bridge",
	version: "0.1.0",
	description: "Emits a tool.call substrate event after every Muse tool call.",
	compat: { source: "native", manifestDir: ".muse-plugin" },
	capabilities: {
		skills: [],
		commands: [],
		hooks: [
			{
				id: HOOK_ID,
				event: "PostToolUse",
				command: [BUN_BIN, "hooks/post-tool-use.ts"],
				timeoutMs: 3000,
				statusMessage: "Recording tool call in the substrate",
			},
		],
		mcpServers: [],
		reminders: [],
	},
};

/**
 * The hook script itself, as literal source lines (not one template
 * literal) so this generator file never has to escape the hook script's own
 * backticks and `${...}` interpolations against its own.
 */
const HOOK_SCRIPT_LINES = [
	"#!/usr/bin/env bun",
	"/**",
	" * Muse PostToolUse hook. Emits one `tool.call` event (surface `muse`) per",
	" * tool call, reusing collectors/src/grok.ts's fail-open emit shape: short",
	" * timeout, bearer token when set, neutral return on any failure, never a",
	" * non-zero exit that could interfere with a Muse turn. Generated by",
	" * packages/projector/src/muse.ts — edit that, not this file.",
	" */",
	'import { spawnSync } from "node:child_process";',
	'import { redact, redactValue } from "__REDACT_MODULE__";',
	"",
	'const SUBSTRATE_URL = (process.env.SUBSTRATE_URL ?? "http://127.0.0.1:7410").replace(/\\/+$/, "");',
	"",
	"async function readStdin(): Promise<string> {",
	"\tconst chunks: Buffer[] = [];",
	"\tfor await (const chunk of process.stdin) chunks.push(chunk as Buffer);",
	'\treturn Buffer.concat(chunks).toString("utf8");',
	"}",
	"",
	"/** Repo root and branch for the hook's working directory, or undefined outside a git repo. */",
	"function repoContext(): { repo: string | undefined; branch: string | undefined } {",
	'\tconst root = spawnSync("git", ["rev-parse", "--show-toplevel"], { encoding: "utf8" });',
	"\tconst repo = root.status === 0 ? root.stdout.trim() || undefined : undefined;",
	'\tconst head = spawnSync("git", ["rev-parse", "--abbrev-ref", "HEAD"], { encoding: "utf8" });',
	"\tconst branch = head.status === 0 ? head.stdout.trim() || undefined : undefined;",
	"\treturn { repo, branch };",
	"}",
	"",
	"try {",
	"\tconst raw = await readStdin();",
	"\tconst payload = raw ? (JSON.parse(raw) as Record<string, unknown>) : {};",
	'\tconst toolName = typeof payload.tool_name === "string" ? payload.tool_name : "unknown";',
	'\tconst sessionId = typeof payload.session_id === "string" ? payload.session_id : undefined;',
	'\tconst toolUseId = typeof payload.tool_use_id === "string" ? payload.tool_use_id : undefined;',
	"\tconst { repo, branch } = repoContext();",
	"",
	"\tawait fetch(`${SUBSTRATE_URL}/events`, {",
	'\t\tmethod: "POST",',
	"\t\theaders: {",
	'\t\t\t"content-type": "application/json",',
	"\t\t\t...(process.env.SUBSTRATE_TOKEN ? { authorization: `Bearer ${process.env.SUBSTRATE_TOKEN}` } : {}),",
	"\t\t},",
	"\t\tbody: JSON.stringify({",
	'\t\t\tsurface: "muse",',
	'\t\t\tkind: "tool.call",',
	"\t\t\tsummary: redact(`muse called ${toolName}`),",
	"\t\t\tsession_id: sessionId,",
	"\t\t\trepo,",
	"\t\t\tbranch,",
	'\t\t\tactor: "agent",',
	"\t\t\tpayload: redactValue({ tool_name: toolName, tool_use_id: toolUseId }),",
	"\t\t}),",
	"\t\tsignal: AbortSignal.timeout(3000),",
	"\t});",
	"} catch {",
	"\t// Fail open: never block or fail a Muse turn on a substrate outage.",
	"}",
	"process.exit(0);",
	"",
].join("\n");

function hookScriptContent(): string {
	return HOOK_SCRIPT_LINES.replace("__REDACT_MODULE__", REDACT_MODULE);
}

function writeBundle(): void {
	mkdirSync(join(BUNDLE_DIR, ".muse-plugin"), { recursive: true });
	mkdirSync(join(BUNDLE_DIR, "hooks"), { recursive: true });
	writeFileSync(join(BUNDLE_DIR, ".muse-plugin", "plugin.json"), `${JSON.stringify(manifest, null, 2)}\n`);
	writeFileSync(join(BUNDLE_DIR, "hooks", "post-tool-use.ts"), hookScriptContent());
}

interface MuseResult {
	status: number;
	stdout: string;
	stderr: string;
}

function runMuse(args: string[]): MuseResult {
	const result = spawnSync(MUSE_BIN, args, { encoding: "utf8" });
	return { status: result.status ?? 1, stdout: result.stdout ?? "", stderr: result.stderr ?? "" };
}

function fail(step: string, result: MuseResult): never {
	process.stderr.write(`[muse-projector] ${step} failed:\n${result.stdout || result.stderr}\n`);
	process.exit(1);
}

/** Installed plugin ids, from `muse plugins list --json`'s `plugins[].plugin.id`. */
function installedPluginIds(): string[] {
	const result = runMuse(["plugins", "list", "--json"]);
	if (result.status !== 0) return [];
	try {
		const parsed = JSON.parse(result.stdout) as { plugins?: Array<{ plugin?: { id?: string } }> };
		return (parsed.plugins ?? [])
			.map((entry) => entry.plugin?.id)
			.filter((id): id is string => typeof id === "string");
	} catch {
		return [];
	}
}

writeBundle();

const validated = runMuse(["plugins", "validate", BUNDLE_DIR, "--json"]);
if (validated.status !== 0) fail("validate", validated);
try {
	const result = JSON.parse(validated.stdout) as { valid?: boolean; diagnostics?: unknown[] };
	if (result.valid !== true || (result.diagnostics?.length ?? 0) > 0) fail("validate (diagnostics present)", validated);
} catch (cause) {
	process.stderr.write(`[muse-projector] cannot parse validate output: ${String(cause)}\n`);
	process.exit(1);
}

const alreadyInstalled = installedPluginIds().includes(PLUGIN_ID);
const install = alreadyInstalled
	? runMuse(["plugins", "update", PLUGIN_ID, "--json"])
	: runMuse(["plugins", "install", BUNDLE_DIR, "--scope", "user", "--json"]);
if (install.status !== 0) fail(alreadyInstalled ? "update" : "install", install);

const approve = runMuse(["plugins", "approve", PLUGIN_ID, "--json"]);
if (approve.status !== 0) fail("approve", approve);

process.stdout.write(
	`[muse-projector] ${alreadyInstalled ? "updated" : "installed"} plugin "${PLUGIN_ID}" (hook "${HOOK_ID}"), approved\n`,
);
