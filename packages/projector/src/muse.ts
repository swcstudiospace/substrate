#!/usr/bin/env bun
/**
 * Project a native Muse plugin whose PostToolUse hook emits a tool.call
 * substrate event.
 *
 *   bun packages/projector/src/muse.ts [--check | --bundle-only]
 *
 * The bundle is regenerated into MUSE_PLUGIN_DIR. The hook imports ./redact.ts
 * from that bundle and reads hooks/substrate.json for the url, the token file
 * and the state dir. The token value is never written into the bundle.
 * `--bundle-only` writes and validates. `--check` compares the installed
 * copy and changes nothing.
 */
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const MUSE_BIN = process.env.MUSE_BIN ?? "/root/.local/bin/muse";
const DEFAULT_BUN = process.env.SUBSTRATE_BUN_BIN ?? "/root/.local/share/reflex/bun/bin/bun";
const DEFAULT_URL = "http://127.0.0.1:7410";
const DEFAULT_TOKEN_FILE = "/etc/substrate/substrate-collector-muse.env";
const DEFAULT_STATE_DIR = "/var/lib/substrate";
const DEFAULT_BUNDLE_DIR = "/var/lib/substrate/muse-plugin";
const PLUGIN_ID = "substrate";
const HOOK_ID = "post-tool-use";
const REDACT_SOURCE = join(import.meta.dir, "..", "..", "mcp-server", "src", "redact.ts");
const REPO_ROOT = join(import.meta.dir, "..", "..", "..");

export class ProjectionRefused extends Error {
	constructor(message: string) {
		super(message);
		this.name = "ProjectionRefused";
	}
}

export interface SubstrateConfig {
	url: string;
	tokenFile: string;
	stateDir: string;
}

interface MuseResult {
	status: number;
	stdout: string;
	stderr: string;
}

interface BundleFiles {
	manifest: string;
	hook: string;
	redact: string;
	config: string;
}

export function sha256Hex(input: string): string {
	return new Bun.CryptoHasher("sha256").update(input).digest("hex");
}

export function substrateConfig(env: NodeJS.ProcessEnv = process.env): SubstrateConfig {
	return {
		url: env.SUBSTRATE_URL?.trim() || DEFAULT_URL,
		tokenFile: env.SUBSTRATE_MUSE_TOKEN_FILE?.trim() || DEFAULT_TOKEN_FILE,
		stateDir: env.SUBSTRATE_STATE_DIR?.trim() || DEFAULT_STATE_DIR,
	};
}

function pluginManifest(bunBin: string): unknown {
	return {
		schemaVersion: 1,
		name: PLUGIN_ID,
		displayName: "Substrate Event Bridge",
		version: "0.1.0",
		description: "Emits a tool.call substrate event after every Muse tool call.",
		compat: { source: "native", manifestDir: ".muse-plugin" },
		capabilities: {
			skills: [],
			commands: [],
			hooks: [
				{
					id: HOOK_ID,
					event: "PostToolUse",
					command: [bunBin, "hooks/post-tool-use.ts"],
					timeoutMs: 3000,
					statusMessage: "Recording tool call in the substrate",
				},
			],
			mcpServers: [],
			reminders: [],
		},
	};
}

/**
 * The hook, as literal source lines, so this file never interpolates the
 * hook's own `${...}` and the import line stays inside a string.
 */
const HOOK_LINES = [
	"#!/usr/bin/env bun",
	"/**",
	" * Muse PostToolUse hook. Emits one tool.call (surface muse) per tool call.",
	" * Generated by packages/projector/src/muse.ts — edit that, not this file.",
	" */",
	'import { appendFileSync, mkdirSync, readFileSync } from "node:fs";',
	'import { spawnSync } from "node:child_process";',
	'import { redact, redactValue } from "./redact.ts";',
	"",
	"const HOOK_BUDGET_MS = 1500;",
	"",
	"// One deadline bounds the whole hook: the stdin read, git and the POST share it.",
	"const deadline = Date.now() + HOOK_BUDGET_MS;",
	"",
	"function remainingMs(): number {",
	"\treturn Math.max(0, deadline - Date.now());",
	"}",
	"",
	"const MAX_ERROR_CHARS = 200;",
	"",
	"interface HookConfig {",
	"\turl: string;",
	"\ttokenFile: string;",
	"\tstateDir: string;",
	"}",
	"",
	"function readConfig(): HookConfig | null {",
	"\ttry {",
	'\t\tconst parsed = JSON.parse(readFileSync(new URL("./substrate.json", import.meta.url), "utf8")) as Partial<HookConfig>;',
	'\t\tif (typeof parsed.url !== "string" || typeof parsed.tokenFile !== "string" || typeof parsed.stateDir !== "string") return null;',
	"\t\treturn { url: parsed.url, tokenFile: parsed.tokenFile, stateDir: parsed.stateDir };",
	"\t} catch {",
	"\t\treturn null;",
	"\t}",
	"}",
	"",
	"function tokenFrom(file: string): string {",
	"\ttry {",
	'\t\tfor (const line of readFileSync(file, "utf8").split("\\n")) {',
	"\t\t\tconst trimmed = line.trim();",
	'\t\t\tif (!trimmed.startsWith("SUBSTRATE_TOKEN=")) continue;',
	'\t\t\tconst raw = trimmed.slice("SUBSTRATE_TOKEN=".length).trim();',
	'\t\t\tif (raw.length >= 2 && ((raw.startsWith("\'") && raw.endsWith("\'")) || (raw.startsWith(\'"\') && raw.endsWith(\'"\')))) return raw.slice(1, -1);',
	'\t\t\treturn raw;',
	"\t\t}",
	"\t} catch {",
	'\t\treturn "";',
	"\t}",
	'\treturn "";',
	"}",
	"",
	"async function readStdin(timeoutMs: number): Promise<string> {",
	"\tlet resolveTimeout: (value: string) => void = () => {};",
	"\tconst timeout = new Promise<string>((resolve) => {",
	"\t\tresolveTimeout = resolve;",
	"\t});",
	"\tconst timer = setTimeout(() => resolveTimeout(\"\"), timeoutMs);",
	"\ttry {",
	"\t\treturn await Promise.race([Bun.stdin.text(), timeout]);",
	"\t} catch {",
	'\t\treturn "";',
	"\t} finally {",
	"\t\tclearTimeout(timer);",
	"\t}",
	"}",
	"",
	"function repoContext(): { repo?: string; branch?: string } {",
	'\tconst origin = spawnSync("git", ["remote", "get-url", "origin"], { encoding: "utf8", timeout: Math.max(1, remainingMs()) });',
	'\tconst pattern = new RegExp("[:/]([^/:]+/[^/]+?)(?:\\\\.git)?$");',
	"\tconst repo = origin.status === 0 ? origin.stdout.trim().match(pattern)?.[1] : undefined;",
	'\tconst head = spawnSync("git", ["rev-parse", "--abbrev-ref", "HEAD"], { encoding: "utf8", timeout: Math.max(1, remainingMs()) });',
	'\tconst name = head.status === 0 ? head.stdout.trim() : "";',
	'\tconst branch = name && name !== "HEAD" ? name : undefined;',
	"\treturn { repo, branch };",
	"}",
	"",
	"function recordRefusal(stateDir: string, status: number, error: string): void {",
	"\tconst safe = redact(error).slice(0, MAX_ERROR_CHARS);",
	"\tconst line = JSON.stringify({",
	"\t\tts: new Date().toISOString(),",
	'\t\tcollector: "muse",',
	'\t\tsource: "muse.tool_call",',
	'\t\tkind: "tool.call",',
	'\t\tsurface: "muse",',
	"\t\tstatus,",
	"\t\terror: safe,",
	"\t});",
	"\ttry {",
	"\t\tmkdirSync(stateDir, { recursive: true });",
	'\t\tappendFileSync(`${stateDir.replace(/\\/+$/, "")}/refused-emits.jsonl`, `${line}\\n`);',
	"\t} catch {",
	"\t\t// The turn still ends cleanly.",
	"\t}",
	"\ttry {",
	"\t\tprocess.stderr.write(",
	"\t\t\t`[collectors] refused emit collector=muse source=muse.tool_call status=${status} error=${safe}\\n`,",
	"\t\t);",
	"\t} catch {",
	"\t\t// Never throw from a reporting path.",
	"\t}",
	"}",
	"",
	"try {",
	"\tconst cfg = readConfig();",
	"\tif (cfg) {",
	"\t\tconst raw = await readStdin(remainingMs());",
	"\t\tconst payload = raw ? (JSON.parse(raw) as Record<string, unknown>) : {};",
	'\t\tconst tool = typeof payload.tool_name === "string" && payload.tool_name ? payload.tool_name : "unknown";',
	'\t\tconst sessionId = typeof payload.session_id === "string" ? payload.session_id : undefined;',
	"\t\tconst fields: Record<string, unknown> = { tool };",
	'\t\tif (typeof payload.outcome === "string") fields.outcome = payload.outcome;',
	'\t\tif (typeof payload.duration_ms === "number") fields.duration_ms = payload.duration_ms;',
	'\t\tif (typeof payload.tool_use_id === "string") fields.tool_use_id = payload.tool_use_id;',
	"\t\tconst { repo, branch } = repoContext();",
	"\t\tconst token = tokenFrom(cfg.tokenFile);",
	"\t\tlet base = cfg.url;",
	'\t\twhile (base.endsWith("/")) base = base.slice(0, -1);',
	'\t\tconst response = await fetch(`${base}/events`, {',
	'\t\t\tmethod: "POST",',
	"\t\t\theaders: {",
	'\t\t\t\t"content-type": "application/json",',
	'\t\t\t\t...(token ? { authorization: `Bearer ${token}` } : {}),',
	"\t\t\t},",
	"\t\t\tbody: JSON.stringify({",
	'\t\t\t\tsurface: "muse",',
	'\t\t\t\tkind: "tool.call",',
	'\t\t\t\tactor: "agent",',
	"\t\t\t\tsummary: redact(`muse called ${tool}`),",
	"\t\t\t\t...(sessionId ? { session_id: sessionId } : {}),",
	"\t\t\t\t...(repo ? { repo } : {}),",
	"\t\t\t\t...(branch ? { branch } : {}),",
	"\t\t\t\tpayload: redactValue(fields),",
	"\t\t\t}),",
	"\t\t\tsignal: AbortSignal.timeout(remainingMs()),",
	"\t\t});",
	"\t\tif (response.status >= 400 && response.status < 500) {",
	"\t\t\tlet error = `http ${response.status}`;",
	"\t\t\ttry {",
	"\t\t\t\tconst body = (await response.json()) as { error?: unknown };",
	'\t\t\t\tif (typeof body.error === "string") error = body.error;',
	"\t\t\t} catch {",
	"\t\t\t\t// Keep the status text.",
	"\t\t\t}",
	"\t\t\trecordRefusal(cfg.stateDir, response.status, error);",
	"\t\t}",
	"\t}",
	"} catch {",
	"\t// Fail open: never block a Muse turn.",
	"}",
	"process.exit(0);",
	"",
];

export function hookSource(): string {
	return HOOK_LINES.join("\n");
}

function assertCopyable(source: string): void {
	for (const line of source.split("\n")) {
		const trimmed = line.trim();
		if (trimmed.startsWith("//") || trimmed.startsWith("*") || trimmed.startsWith("/*")) continue;
		if (/^\s*import\b/.test(line) || /\brequire\s*\(/.test(line) || /^\s*export\s+.+\bfrom\b/.test(line)) {
			throw new ProjectionRefused("redact.ts contains an import or require; refusing to copy it");
		}
	}
}

function sourceCommit(): string {
	const result = spawnSync("git", ["log", "-1", "--format=%H", "--", "packages/mcp-server/src/redact.ts"], {
		cwd: REPO_ROOT,
		encoding: "utf8",
	});
	const commit = (result.stdout ?? "").trim();
	if (result.status !== 0 || !/^[0-9a-f]{40}$/.test(commit)) {
		throw new ProjectionRefused("cannot record the redact.ts source commit");
	}
	return commit;
}

export function assembleBundle(env: NodeJS.ProcessEnv = process.env): BundleFiles {
	const source = readFileSync(REDACT_SOURCE, "utf8");
	assertCopyable(source);
	const commit = sourceCommit();
	const digest = sha256Hex(source);
	const header = `// Generated by packages/projector/src/muse.ts from packages/mcp-server/src/redact.ts — commit ${commit}, sha256 ${digest}\n`;
	const files: BundleFiles = {
		manifest: `${JSON.stringify(pluginManifest(env.SUBSTRATE_BUN_BIN?.trim() || DEFAULT_BUN), null, 2)}\n`,
		hook: hookSource(),
		redact: `${header}${source}`,
		config: `${JSON.stringify(substrateConfig(env), null, 2)}\n`,
	};
	const token = env.SUBSTRATE_TOKEN?.trim() ?? "";
	if (token && Object.values(files).some((blob) => blob.includes(token))) {
		throw new ProjectionRefused("refusing to write a token value into the muse bundle");
	}
	return files;
}

export function writeBundle(dir: string, files: BundleFiles = assembleBundle()): void {
	mkdirSync(join(dir, ".muse-plugin"), { recursive: true });
	mkdirSync(join(dir, "hooks"), { recursive: true });
	writeFileSync(join(dir, ".muse-plugin", "plugin.json"), files.manifest);
	writeFileSync(join(dir, "hooks", "post-tool-use.ts"), files.hook);
	writeFileSync(join(dir, "hooks", "redact.ts"), files.redact);
	writeFileSync(join(dir, "hooks", "substrate.json"), files.config);
}

function runMuse(args: string[]): MuseResult {
	const result = spawnSync(MUSE_BIN, args, { encoding: "utf8" });
	return { status: result.status ?? 1, stdout: result.stdout ?? "", stderr: result.stderr ?? "" };
}

class MuseFailed extends Error {
	constructor(step: string) {
		super(step);
		this.name = "MuseFailed";
	}
}

function fail(step: string, result: MuseResult): never {
	process.stderr.write(`[muse-projector] ${step} failed:\n${result.stdout || result.stderr}\n`);
	throw new MuseFailed(step);
}

function requireValid(result: MuseResult): void {
	if (result.status !== 0) fail("validate", result);
	let parsed: { valid?: boolean; diagnostics?: unknown[] };
	try {
		parsed = JSON.parse(result.stdout) as { valid?: boolean; diagnostics?: unknown[] };
	} catch (cause) {
		process.stderr.write(`[muse-projector] cannot parse validate output: ${String(cause)}\n`);
		throw new MuseFailed("validate");
	}
	if (parsed.valid !== true || (parsed.diagnostics?.length ?? 0) > 0) fail("validate (diagnostics present)", result);
}

function installedPluginIds(): string[] {
	const result = runMuse(["plugins", "list", "--json"]);
	if (result.status !== 0) return [];
	try {
		const parsed = JSON.parse(result.stdout) as { plugins?: Array<{ plugin?: { id?: string } }> };
		return (parsed.plugins ?? []).map((entry) => entry.plugin?.id).filter((id): id is string => typeof id === "string");
	} catch {
		return [];
	}
}

function bundleDir(env: NodeJS.ProcessEnv = process.env): string {
	return env.MUSE_PLUGIN_DIR?.trim() || DEFAULT_BUNDLE_DIR;
}

function usage(message: string): never {
	process.stderr.write(`[projector] ${message}\nusage: muse.ts [--check | --bundle-only]\n`);
	process.exit(2);
}

function fileSha(path: string): string | null {
	try {
		return sha256Hex(readFileSync(path, "utf8"));
	} catch {
		return null;
	}
}

function checkInstalled(projected: BundleFiles): string[] {
	const listed = runMuse(["plugins", "list", "--json"]);
	if (listed.status !== 0) return ["list"];
	let cache: string | undefined;
	try {
		const parsed = JSON.parse(listed.stdout) as {
			plugins?: Array<{ plugin?: { id?: string }; record?: { cache_path?: string } }>;
		};
		cache = (parsed.plugins ?? []).find((entry) => entry.plugin?.id === PLUGIN_ID)?.record?.cache_path;
	} catch {
		return ["list"];
	}
	if (!cache) return ["not-installed"];
	const inspected = runMuse(["plugins", "inspect", PLUGIN_ID, "--json"]);
	if (inspected.status !== 0) return ["inspect"];
	try {
		const parsed = JSON.parse(inspected.stdout) as { runtime_capabilities?: Array<{ status?: string }> };
		const caps = parsed.runtime_capabilities ?? [];
		if (caps.length === 0 || caps.some((cap) => cap.status !== "trusted_enabled")) return ["trust"];
	} catch {
		return ["inspect"];
	}
	const expected: Record<string, string> = {
		".muse-plugin/plugin.json": sha256Hex(projected.manifest),
		"hooks/post-tool-use.ts": sha256Hex(projected.hook),
		"hooks/redact.ts": sha256Hex(projected.redact),
		"hooks/substrate.json": sha256Hex(projected.config),
	};
	const drifted = Object.entries(expected)
		.filter(([rel, digest]) => fileSha(join(cache, rel)) !== digest)
		.map(([rel]) => rel);
	return drifted;
}

function project(dir: string): BundleFiles {
	const files = assembleBundle();
	writeBundle(dir, files);
	return files;
}

function main(argv: string[]): number {
	const known = new Set(["--check", "--bundle-only"]);
	const unknown = argv.filter((arg) => !known.has(arg));
	if (unknown.length > 0) usage(`unknown argument ${unknown[0]}`);
	const checkOnly = argv.includes("--check");
	const bundleOnly = argv.includes("--bundle-only");
	if (checkOnly && bundleOnly) usage("give only one of --check, --bundle-only");

	if (checkOnly) {
		const dir = join(tmpdir(), `muse-check-${process.pid}`);
		try {
			const files = project(dir);
			requireValid(runMuse(["plugins", "validate", dir, "--json"]));
			const drifted = checkInstalled(files);
			if (drifted.length === 0) {
				process.stdout.write("[muse-projector] already current\n");
				return 0;
			}
			process.stdout.write(`[muse-projector] would change: ${drifted.join(", ")}\n`);
			return 1;
		} finally {
			rmSync(dir, { recursive: true, force: true });
		}
	}

	const dir = bundleDir();
	project(dir);
	requireValid(runMuse(["plugins", "validate", dir, "--json"]));
	if (bundleOnly) {
		process.stdout.write(`[muse-projector] bundle written to ${dir}, validated\n`);
		return 0;
	}

	const alreadyInstalled = installedPluginIds().includes(PLUGIN_ID);
	const install = alreadyInstalled
		? runMuse(["plugins", "update", PLUGIN_ID, "--json"])
		: runMuse(["plugins", "install", dir, "--scope", "user", "--json"]);
	if (install.status !== 0) fail(alreadyInstalled ? "update" : "install", install);
	const approve = runMuse(["plugins", "approve", PLUGIN_ID, "--json"]);
	if (approve.status !== 0) fail("approve", approve);
	process.stdout.write(
		`[muse-projector] ${alreadyInstalled ? "updated" : "installed"} plugin "${PLUGIN_ID}" (hook "${HOOK_ID}"), approved\n`,
	);
	return 0;
}

if (import.meta.main) {
	try {
		process.exit(main(process.argv.slice(2)));
	} catch (cause) {
		if (cause instanceof ProjectionRefused) {
			process.stderr.write(`[projector] refused: ${cause.message}.\n`);
			process.exit(2);
		}
		if (cause instanceof MuseFailed) process.exit(1);
		throw cause;
	}
}
