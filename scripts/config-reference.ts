#!/usr/bin/env bun
/**
 * Config reference generator (`bun run config:reference`).
 *
 *   bun scripts/config-reference.ts [--check]
 *
 * `packages/mcp-server/src/flag-registry.ts` is the one table of every
 * environment variable read by TypeScript under `packages/` and `scripts/`
 * (the Python dispatcher and the infra shell are not covered), and
 * `flag-registry.test.ts` fails when that TypeScript reads a name the table
 * lacks. This script renders it to
 * `docs/config-reference.md` (a table per plane, the promotion policies, the
 * name families, and the exempt platform variables) and splices the evidence
 * table into `docs/runbooks/flag-promotion.md` between its two markers, so the
 * documents cannot drift from the registry the advisor judges against.
 *
 * Default mode writes both files (tmp + rename, so a reader never sees half a
 * file). `--check` writes nothing: it exits 0 when both committed files equal
 * the render, 1 when either differs or the runbook has lost its markers, and
 * says which. `config-reference.test.ts` runs the check on the committed tree.
 * Exit 2 on a usage error.
 *
 * It renders names, defaults and thresholds only; it never reads an
 * environment file or a variable's value. The evidence thresholds are printed
 * as PROPOSED, the registry's own word for them.
 */
import { existsSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
	type Evidence,
	FLAG_FAMILIES,
	FLAG_PLANES,
	FLAG_PLANE_TITLES,
	FLAGS,
	type FlagSpec,
	REGISTRY_EXEMPT,
	policyFlags,
} from "../packages/mcp-server/src/flag-registry.ts";

const ROOT = join(import.meta.dir, "..");
export const REFERENCE_PATH = "docs/config-reference.md";
export const RUNBOOK_PATH = "docs/runbooks/flag-promotion.md";
export const EVIDENCE_BEGIN = "<!-- evidence-table:begin (generated by `bun run config:reference`; edit flag-registry.ts, not this table) -->";
export const EVIDENCE_END = "<!-- evidence-table:end -->";

/** A table cell: no pipe, no newline, so the registry's `a | b` value lists survive. */
function cell(text: string): string {
	return text.replace(/\|/g, "\\|").replace(/\n/g, " ");
}

function code(text: string): string {
	return `\`${text.replace(/`/g, "")}\``;
}

function flagRow(flag: FlagSpec): string {
	const notes = [flag.status === "unread" ? "UNREAD: no code reads it today" : null, flag.status === "legacy" ? "LEGACY: read only to warn at boot" : null, flag.status === "shell" ? "SHELL: read by the infra shell file named in `Read by`, not by the server" : null].filter((note) => note !== null);
	const unset = notes.length > 0 ? `${flag.unset} (${notes.join("; ")})` : flag.unset;
	const doc = flag.doc === undefined ? "" : `. See \`${flag.doc}\``;
	return `| ${code(flag.name)} | ${flag.kind} | ${cell(flag.default)} | ${cell(flag.allowed)} | ${cell(unset + doc)} | ${cell(flag.readBy)} | ${flag.documented ? "yes" : "no"} |`;
}

function describeEvidence(evidence: Evidence): string {
	const term = (item: { series: string; labels?: readonly string[] }): string => (item.labels === undefined ? item.series : `${item.series}{${item.labels.join("+")}}`);
	const quantity =
		evidence.stat === "share"
			? `${term(evidence.numerator)} / ${term(evidence.denominator ?? { series: evidence.numerator.series })}`
			: evidence.stat === "ratio"
				? `${term(evidence.numerator)} per ${term(evidence.denominator ?? evidence.numerator)} observation`
				: evidence.stat === "max"
					? `worst ${term(evidence.numerator)}`
					: `total ${term(evidence.numerator)}`;
	const threshold = evidence.unit === "share" ? `${(evidence.threshold * 100).toFixed(2)} %` : `${evidence.threshold}${evidence.unit === "count" ? "" : ` ${evidence.unit}`}`;
	return `${quantity} ${evidence.comparator} ${threshold}`;
}

/** The evidence table: one row per criterion, every threshold a proposal. */
export function renderEvidenceTable(): string {
	const rows = ["| Flag | Criterion | Rule | Min samples | Window | Series | Rationale |", "| --- | --- | --- | --- | --- | --- | --- |"];
	for (const flag of policyFlags()) {
		for (const evidence of flag.policy?.evidence ?? []) {
			rows.push(
				`| ${code(flag.name)} | ${cell(evidence.id)} | ${cell(code(describeEvidence(evidence)))} | ${evidence.minSamples} | ${evidence.window} | ${evidence.needs} | ${cell(evidence.rationale)} |`,
			);
		}
	}
	return `${rows.join("\n")}\n`;
}

/** The runbook with the evidence table between its markers replaced; `null` when the markers are missing or out of order. */
export function spliceEvidence(runbook: string, table: string): string | null {
	const begin = runbook.indexOf(EVIDENCE_BEGIN);
	const end = runbook.indexOf(EVIDENCE_END);
	if (begin < 0 || end < begin) return null;
	return `${runbook.slice(0, begin + EVIDENCE_BEGIN.length)}\n\n${table}\n${runbook.slice(end)}`;
}

export function renderReference(): string {
	const out: string[] = [
		"# Configuration reference",
		"",
		"Every environment variable read by TypeScript under `packages/` and `scripts/` (tests excluded), by plane. **Not covered: the Python dispatcher and the infra shell** (`infra/vps/*.sh`); a variable read only there (the dispatcher's `SUBSTRATE_DISPATCH_*` settings, the health-probe settings of the shell units, `BOOT_GATE` and `CI_ENABLED` in the CI workflow) has no row, except the few shell-read operator switches the registry lists on purpose (rows flagged SHELL: the two deploy-hook modes). **Generated** from `packages/mcp-server/src/flag-registry.ts` by `bun run config:reference`; do not edit it by hand (`bun run config:reference -- --check` exits 1 when it has drifted, and `config-reference.test.ts` runs that check). `flag-registry.test.ts` fails when that TypeScript reads a name the registry does not list, so a flag read there cannot ship undocumented; the scanner's remaining blind spots are listed in `flag-registry-scan.ts`.",
		"",
		"How to read a row: **Default** is what the code uses when the variable is unset or invalid; **Unset** says what that means in practice; **Read by** is descriptive (the owning reader). **In `.env.example`** says whether `.env.example` carries a `NAME=` line (live or commented). Values are never shown for a secret reference: those variables hold credentials, and the reference names them only.",
		"",
		"Which environment a name belongs in is part of the row: the server's shared env file, a unit drop-in (the sweep, the doctor, the watchdog) or a host/client environment. `docs/runbooks/flag-promotion.md` says when a policy flag is safe to flip; the table of promotion policies below is the registry's view of it.",
		"",
	];
	for (const plane of FLAG_PLANES) {
		const flags = FLAGS.filter((flag) => flag.plane === plane);
		const families = FLAG_FAMILIES.filter((family) => family.plane === plane);
		if (flags.length === 0 && families.length === 0) continue;
		out.push(`## ${FLAG_PLANE_TITLES[plane]}`, "", "| Name | Kind | Default | Allowed | Unset means | Read by | In `.env.example` |", "| --- | --- | --- | --- | --- | --- | --- |");
		for (const flag of flags) out.push(flagRow(flag));
		for (const family of families) {
			const doc = family.doc === undefined ? "" : `. See \`${family.doc}\``;
			out.push(`| ${cell(code(family.pattern))} | ${family.kind} | ${cell(family.default)} | ${cell(family.allowed)} | ${cell(family.unset + doc)} | ${cell(family.readBy)} | ${family.documentedMembers.length > 0 ? "yes" : "no"} |`);
		}
		out.push("");
	}

	out.push(
		"## Promotion policies",
		"",
		"The policy flags: the value that preserves today's behaviour or only reports (**safe**), the value that makes the policy bite (**enforcing**), the operator's step and the rollback. Code never performs a flip. A flag with evidence is judged by `bun run advisor:promote` against the PROPOSED thresholds in `docs/runbooks/flag-promotion.md`; a flag without evidence has a manual check instead. Extended-series criteria are judged only when the extended gauge covers the window AND the policy's own series has been recording for at least 90 % of it (a policy records nothing while its flag is off; a series with no points cannot tell not-observed from zero), as `docs/runbooks/flag-promotion.md` states exactly. A flag with BOTH has a manual check that still applies when the advisor says `ready`: the advisor prints it as `also check:` and carries it in its JSON.",
		"",
		"| Flag | Safe | Enforcing | Step | Rollback | Evidence |",
		"| --- | --- | --- | --- | --- | --- |",
	);
	for (const flag of policyFlags()) {
		const policy = flag.policy;
		if (policy === undefined) continue; // policyFlags() only returns flags that have one
		const also = policy.manual === undefined ? "" : `; ALSO manual (applies even when the advisor says ready): ${policy.manual}`;
		const evidence = policy.evidence.length > 0 ? `${policy.evidence.map((item) => `${item.id} (${item.needs})`).join("; ")}${also}` : `manual: ${policy.manual ?? "none"}`;
		out.push(`| ${code(flag.name)} | ${code(policy.safe)} | ${code(policy.enforcing)} | ${cell(policy.step)} | ${cell(policy.rollback)} | ${cell(evidence)} |`);
	}
	out.push("", "## Names composed at run time", "", "The scan sees only the prefix of a name the code builds, so each family is registered by pattern and by the members it can read.", "", "| Pattern | Prefix | Members |", "| --- | --- | --- |");
	for (const family of FLAG_FAMILIES) out.push(`| ${cell(code(family.pattern))} | ${code(family.prefix)} | ${family.members.length} |`);
	out.push("", "## Names that are not configuration", "", "Read or touched by the code but not Agent Substrate settings; `flag-registry.test.ts` accepts a read of these without a row.", "", "| Name | Why exempt |", "| --- | --- |");
	for (const entry of REGISTRY_EXEMPT) out.push(`| ${code(entry.name)} | ${cell(entry.reason)} |`);
	out.push("");
	return out.join("\n");
}

export interface Io {
	stdout(text: string): void;
	stderr(text: string): void;
	root?: string;
}

function readIfExists(path: string): string | null {
	return existsSync(path) ? readFileSync(path, "utf8") : null;
}

function writeAtomic(path: string, text: string): void {
	const tmp = `${path}.tmp-${process.pid}`;
	writeFileSync(tmp, text);
	renameSync(tmp, path);
}

export function main(argv: readonly string[], io: Io = { stdout: (text) => process.stdout.write(text), stderr: (text) => process.stderr.write(text) }): number {
	const stray = argv.find((arg) => arg !== "--check");
	if (stray !== undefined) {
		io.stderr(`config reference: unknown argument ${stray}\nusage: bun scripts/config-reference.ts [--check]\n`);
		return 2;
	}
	const check = argv.includes("--check");
	const root = io.root ?? ROOT;
	const referencePath = join(root, REFERENCE_PATH);
	const runbookPath = join(root, RUNBOOK_PATH);

	const reference = renderReference();
	const runbook = readIfExists(runbookPath);
	const spliced = runbook === null ? null : spliceEvidence(runbook, renderEvidenceTable());
	if (spliced === null) {
		io.stderr(`config reference: ${RUNBOOK_PATH} is missing or has lost its evidence-table markers\n`);
		return 1;
	}
	if (check) {
		const drift = [readIfExists(referencePath) === reference ? null : REFERENCE_PATH, runbook === spliced ? null : RUNBOOK_PATH].filter((path) => path !== null);
		if (drift.length > 0) {
			io.stderr(`config reference: ${drift.join(" and ")} drifted from the registry; run: bun run config:reference\n`);
			return 1;
		}
		io.stdout("config reference: up to date\n");
		return 0;
	}
	writeAtomic(referencePath, reference);
	writeAtomic(runbookPath, spliced);
	io.stdout(`config reference: wrote ${REFERENCE_PATH} and the evidence table in ${RUNBOOK_PATH}\n`);
	return 0;
}

if (import.meta.main) process.exit(main(process.argv.slice(2)));
